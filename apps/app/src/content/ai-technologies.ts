export type AiTechnologyStage = "knowledge" | "persona" | "evaluation";

/**
 * Технический разбор одного механизма стратегии.
 *
 * Здесь живёт то, что нельзя увидеть из продуктового описания: промпты,
 * схемы, формулы ранжирования, ключи кэша, порядок вызовов и то, какие
 * оговорки реализации знает автор кода.
 */
export interface AiTechnologyInternal {
  title: string;
  detail: string;
}

export interface AiTechnologyImplementation {
  /** id стратегии в реестре этапа конвейера. */
  strategyId: string;
  /** Файлы реализации относительно корня репозитория. */
  files: string[];
  /** Сколько и каких обращений к модели добавляет технология. */
  llmCalls: string;
  /** Схемы структурированного вывода, которыми валидируется ответ модели. */
  schemas: string[];
  /** Поля телеметрии, по которым технологию видно в проде и в отчёте стенда. */
  telemetry: string[];
}

/**
 * `measured` — по варианту есть успешные диалоги; `no-data` — прогон
 * не состоялся, и нулевые Δ в отчёте означают отсутствие замера.
 */
export type AiBenchmarkStatus = "measured" | "no-data";

export interface AiBenchmarkMetricRow {
  metric: string;
  delta: string;
  ci: string;
  pValue: string;
  pairs: string;
  verdict: string;
}

export interface AiBenchmarkArmRow {
  arm: string;
  role: "control" | "candidate";
  dialogs: string;
  mae: string;
  withinFixtureSd: string;
  styleKappa: string;
  criteriaF1: string;
  latency: string;
  tokens: string;
}

/** Отчёт офлайн-стенда: новая технология против классического подхода. */
export interface AiTechnologyBenchmark {
  status: AiBenchmarkStatus;
  /** Одна фраза: что показал замер против контрольного варианта. */
  headline: string;
  reportLabel: string;
  reportPath: string;
  runAt: string;
  provider: string;
  model: string;
  scenarios: string;
  control: string;
  metrics: AiBenchmarkMetricRow[];
  arms: AiBenchmarkArmRow[];
  caveats: string[];
  reproduce: string;
}

export interface AiTechnology {
  slug: string;
  name: string;
  shortName: string;
  variantId: string;
  referenceVariantId: string;
  stage: AiTechnologyStage;
  stageLabel: string;
  icon: TablerIcon;
  eyebrow: string;
  summary: string;
  plainLanguage: string;
  customerOutcome: string;
  computeLabel: string;
  computeDescription: string;
  flow: Array<{ title: string; description: string }>;
  /** Инженерное резюме: что именно происходит в коде, в двух-трёх фразах. */
  technicalSummary: string;
  internals: AiTechnologyInternal[];
  implementation: AiTechnologyImplementation;
  benchmark: AiTechnologyBenchmark;
  benefits: Array<{ title: string; description: string }>;
  useWhen: string[];
  limits: string[];
  measurements: Array<{
    metric: string;
    question: string;
    successSignal: string;
  }>;
  fallback: string;
  parameters: Array<{
    name: string;
    defaultValue: string;
    meaning: string;
  }>;
  source: {
    label: string;
    url: string;
    note: string;
  };
}

